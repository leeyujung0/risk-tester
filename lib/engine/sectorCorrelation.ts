// - 반도체/IT ↔ 반도체/IT (0.75): 국내 대형 반도체주는 같은 업황 사이클과
//   수출 실적 발표에 동시에 반응해 매우 높은 동조화를 보임.
// - 플랫폼/성장주 ↔ 플랫폼/성장주 (0.70): 금리·밸류에이션 부담을 공유하는
//   성장주 특성상 높은 동조화.
// - 금융 ↔ 금융 (0.70): 은행/금융지주는 정책금리와 경기 민감도를 공유해
//   높은 동조화.
// - 수출제조업 ↔ 수출제조업 (0.60): 업종은 달라도 환율·글로벌 경기 노출을
//   공유.
// - 내수/소비재 ↔ 내수/소비재 (0.45): 사업 구조가 상대적으로 이질적이라
//   동조화는 중간 수준.
// - 반도체/IT ↔ 플랫폼/성장주 (0.55): 둘 다 '성장주' 성격을 공유해 상대적으로
//   높음.
// - 반도체/IT ↔ 수출제조업 (0.40): 수출 사이클은 공유하지만 업종 성격은 다름.
// - 플랫폼/성장주 ↔ 수출제조업 (0.30): 성장주 vs 가치주 성격 차이로 낮은 편.
// - 금융 ↔ 그 외 섹터 (0.20~0.30): 정책금리 민감도가 상대적으로 독립적이라
//   낮은 편.
// - 내수/소비재 ↔ 그 외 섹터 (0.20~0.30): 내수 특성상 수출/성장주와의
