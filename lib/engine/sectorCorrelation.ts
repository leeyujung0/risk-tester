/**
 * 테이블에 없는 섹터 조합이 들어올 경우의 기본값.
 * 새 섹터가 SAMPLE_UNIVERSE에 추가됐는데 이 표를 갱신하지 않아도
 * (상관관계를 다소 보수적으로 잡을 뿐) 시뮬레이션이 죽지 않도록 하는 안전장치.
 */
const DEFAULT_SECTOR_CORRELATION = 0.25;

export function getSectorCorrelation(sectorA: string, sectorB: string): number {
  return (
    SECTOR_CORRELATION[sectorA]?.[sectorB] ??
    SECTOR_CORRELATION[sectorB]?.[sectorA] ??
    DEFAULT_SECTOR_CORRELATION
  );
}
